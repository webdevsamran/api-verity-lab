def _yaml(task: dict[str, Any]) -> str:
    """Dump with literal blocks for multi-line strings.

    The default representer emits a double-quoted scalar with every newline
    escaped, which turns an embedded manifest into one unreadable line. A task
    pack is read by the person deciding whether to trust it, so the readable
    form is the correct one.
    """
    import yaml

    class _Dumper(yaml.SafeDumper):
        pass

    def _string(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
        if "\n" in value:
            return dumper.represent_scalar("tag:yaml.org,2002:str", value, style="|")
        return dumper.represent_scalar("tag:yaml.org,2002:str", value)

    _Dumper.add_representer(str, _string)
    return yaml.dump(task, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=100)


def readme(built: Pack, provenance: dict[str, Any]) -> str:
    """The pack's own account of where it came from and what is missing.

    A generated benchmark with no provenance is a benchmark nobody can check,
    and the skipped list matters more than the exported one: a reader comparing
    tool count to task count will otherwise assume the difference was an error.
    """
    lines = [
        f"# {built.name}",
        "",
        "Generated by `apiverity agent-tasks` from a verified MCP tool manifest.",
        "Do not edit by hand: re-run the command.",
        "",
        "| | |",
        "|---|---|",
        f"| Manifest | `{provenance.get('manifest')}` |",
        f"| Contract hash | `{provenance.get('contract_hash')}` |",
        f"| Generated by | api-verity-lab {provenance.get('tool_version')} |",
        f"| Tasks | {len(built.tasks)} |",
        "",
        "## What each task measures",
        "",
        "Given the manifest, write the arguments for one call to a tool. The tool's own",
        "`inputSchema` is the scorer -- a `json_schema` assertion pointed at the schema",
        "this project verified. A tool manifest exists so a caller can construct a valid",
        "call from it; whether an agent can is a fact about the agent, measured against",
        "the contract rather than against somebody's opinion of it.",
        "",
    ]
    if built.findings:
        lines += [
            "## This surface did not pass",
            "",
            "Exported with `--allow-findings`. Every failure below is ambiguous between the",
            "agent and the manifest, and that ambiguity is this pack's, not the agent's.",
            "",
        ]
        lines += [f"- `{f['rule_id']}` ({f['severity']}) {f['message']}" for f in built.findings]
        lines.append("")
    if built.skipped:
        lines += ["## Tools with no task, and why", ""]
        lines += [f"- **{s.name}** — {s.reason}" for s in built.skipped]
        lines.append("")
    return "\n".join(lines)


def write(built: Pack, directory: str | Path, provenance: dict[str, Any]) -> list[Path]:
    target = Path(directory)
    target.mkdir(parents=True, exist_ok=True)
    written = []
    for task in built.tasks:
        path = target / (task["id"].split("/", 1)[1] + ".yaml")
        path.write_text(_yaml(task), encoding="utf-8", newline="\n")
        written.append(path)
    index = target / "README.md"
    index.write_text(readme(built, provenance), encoding="utf-8", newline="\n")
    written.append(index)
    return written


